FLocalizationReport ValidateCatalogs(const std::span<const FTextCatalog> Catalogs, const std::span<const std::string> FileTexts)
{
	FLocalizationReport Report;
	FLocalization Localization;
	if (auto Loaded = Localization.SetCatalogs(Catalogs); !Loaded)
	{
		Report.Errors.push_back(Loaded.error().Message);
	}

	for (std::size_t Index = 0; Index < Catalogs.size(); ++Index)
	{
		const FTextCatalog& Catalog = Catalogs[Index];
		if (Index < FileTexts.size() && FileTexts[Index] != SerializeTextCatalog(Catalog))
		{
			Report.NonCanonical.push_back(std::format("{}/{}", Catalog.Culture, Catalog.Namespace));
		}

		if (Catalog.Culture != SourceCulture)
		{
			continue;
		}

		for (const FTextCatalog& Translation : Catalogs)
		{
			if (Translation.Namespace != Catalog.Namespace || Translation.Culture == SourceCulture)
			{
				continue;
			}

			// Everything wrong with the translation besides what SetCatalogs already reported first.
			for (std::string& Problem : ValidateTranslation(Catalog, Translation))
			{
				if (!std::ranges::contains(Report.Errors, Problem))
				{
					Report.Errors.push_back(std::move(Problem));
				}
			}

			std::set<std::string_view> Translated;
			for (const FCatalogMessage& Message : Translation.Messages)
			{
				Translated.insert(Message.Key);
			}

			for (const FCatalogMessage& Message : Catalog.Messages)
			{
				if (!Translated.contains(Message.Key))
				{
					Report.Missing.push_back(std::format("{}/{}.{}", Translation.Culture, Catalog.Namespace, Message.Key));
				}
			}
		}
	}

	std::ranges::sort(Report.Missing);
	return Report;
}

std::string GenerateTextIdHeader(const FTextCatalog& Source, const std::string_view CatalogPath)
{
	std::vector<const FCatalogMessage*> Messages;
	for (const FCatalogMessage& Message : Source.Messages)
	{
		Messages.push_back(&Message);
	}

	std::ranges::sort(Messages, {}, &FCatalogMessage::Key);
	std::string Header = std::format("// Generated by HertaEditorCmd localization.generate from {}; do not edit.\n\n#pragma once\n\n#include \"Herta/Localization/Localization.h\"\n\nnamespace Herta::Text::{}\n{{\n", CatalogPath, Source.Namespace);
	for (const FCatalogMessage* const Message : Messages)
	{
		std::string Name = Message->Key;
		std::ranges::replace(Name, '.', '_');
		std::ranges::replace(Name, '-', '_');
		Header += std::format("inline constexpr FTextId {}{{\"{}.{}\"}};\n", Name, Source.Namespace, Message->Key);
	}

	Header += "}\n";
	return Header;
}
