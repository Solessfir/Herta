local function EscapeXml(Value)
    return Value:gsub("&", "&amp;"):gsub("<", "&lt;"):gsub(">", "&gt;"):gsub('"', "&quot;"):gsub("'", "&apos;")
end

function HertaGenerateRiderRunConfiguration(RepositoryRoot, Action, VulkanSdk)
    if os.host() ~= "windows" or (Action ~= "vs2022" and Action ~= "vs2026") then
        return
    end

    local Directory = path.join(RepositoryRoot, ".run")
    assert(os.mkdir(Directory))
    local Project = EscapeXml("$PROJECT_DIR$/Intermediate/ProjectFiles/" .. Action .. "/HertaEditor/HertaEditor.vcxproj")
    local Configurations = {}
    for Index, Configuration in ipairs({ "Debug", "Debug-ASan", "Development", "Shipping" }) do
        local Environment = ""
        if Configuration ~= "Shipping" then
            Environment = "\n" .. string.format([[
      <envs>
        <env name="VULKAN_SDK" value="%s" />
        <env name="VK_ADD_LAYER_PATH" value="%s" />
      </envs>]], EscapeXml(VulkanSdk.Root), EscapeXml(VulkanSdk.ValidationLayerDirectory))
        end
        Configurations[#Configurations + 1] = string.format([[
    <configuration_%d setup="1">
      <option name="CONFIGURATION" value="%s" />
      <option name="PLATFORM" value="x64" />
      <option name="CURRENT_LAUNCH_PROFILE" value="Local" />
      <option name="EXE_PATH" value="$PROJECT_DIR$/Binaries/windows/x86_64/%s/HertaEditor.exe" />
      <option name="PROGRAM_PARAMETERS" value="$(LocalDebuggerCommandArguments)" />
      <option name="WORKING_DIRECTORY" value="$PROJECT_DIR$" />
      <option name="PASS_PARENT_ENVS" value="1" />
      <option name="USE_EXTERNAL_CONSOLE" value="0" />
      <option name="PROJECT_FILE_PATH" value="%s" />%s
    </configuration_%d>]], Index, Configuration, Configuration, Project, Environment, Index) .. "\n"
    end

    local ProfilePath = path.join(Directory, "HertaEditor.run.xml")
    local File = assert(io.open(ProfilePath, "w"))
    assert(File:write(string.format([[<component name="ProjectRunConfigurationManager">
  <!-- Generated by Premake. Use a separate profile for personal overrides. -->
  <configuration default="false" name="HertaEditor" type="CppProject" factoryName="C++ Project">
%s
    <option name="DEFAULT_PROJECT_PATH" value="%s" />
    <option name="PROJECT_FILE_PATH" value="%s" />
    <option name="AUTO_SELECT_PRIORITY" value="0" />
    <method v="2">
      <option name="Build" />
    </method>
  </configuration>
</component>
]], table.concat(Configurations), Project, Project)))
    assert(File:close())
end
